#include <iostream>

using namespace std ; 

int main(){
    int a = 10 , b = 20 ;
    cout << " + operator : " << a + b << endl ;
    cout << " - operator : " << a - b << endl ;
    cout << " * operator : " << a * b << endl ;
    cout << " / operator : " << a / b << endl ;
    cout << " % operator : " << a % b << endl ;
    return 0 ; 
}